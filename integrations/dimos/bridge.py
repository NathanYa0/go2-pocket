"""Owned DimOS session. JSON-lines IPC; credentials never cross into the browser."""
from __future__ import annotations

import json
import os
from pathlib import Path
import queue
import signal
import subprocess
import sys
import threading
import time

from dotenv import dotenv_values
import numpy as np
from dimos.porcelain.dimos import Dimos
from dimos.navigation.go2.loop_closure.premap import Premap

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "vendor/dimos"
RUNTIME = ROOT / "output/mapping"
COMMANDS: queue.Queue[str] = queue.Queue()
STOP = threading.Event()


def emit(**data: object) -> None:
    print(json.dumps(data, allow_nan=False, separators=(",", ":")), flush=True)


def receive() -> None:
    for line in sys.stdin:
        try:
            command = json.loads(line)["command"]
            if command == "stop":
                STOP.set()
            else:
                COMMANDS.put(command)
        except (ValueError, KeyError, TypeError):
            continue
    STOP.set()  # parent disappeared


def stop_motion(app: Dimos) -> bool:
    ok = True
    for call in (
        app.WavefrontFrontierExplorer.end_exploration,
        app.ReplanningAStarPlanner.cancel_goal,
        app.GO2Connection.stop_movement,
    ):
        try:
            call()
        except Exception:
            ok = False
    return ok


def preview(points) -> dict:
    xyz = np.asarray(points.points_f32())
    xyz = xyz[np.isfinite(xyz).all(axis=1)]
    xyz = xyz[::max(1, int(np.ceil(len(xyz) / 30000)))]
    return {"points": np.round(xyz, 3).tolist(), "frame": "map", "capturedAt": time.time() * 1000}


def save_preview(run_id: str, cloud: dict) -> None:
    temp = RUNTIME / (run_id + ".json.tmp")
    temp.write_text(json.dumps(cloud, allow_nan=False))
    temp.replace(RUNTIME / (run_id + ".json"))


def main() -> int:
    RUNTIME.mkdir(parents=True, exist_ok=True)
    os.chmod(RUNTIME, 0o700)
    run_id = sys.argv[1]
    # IDs are generated by the owning service, never paths supplied by clients.
    if not run_id.replace("-", "").isalnum():
        raise ValueError("Invalid session ID")
    map_path = RUNTIME / (run_id + ".map.db")
    env = os.environ.copy()
    values = dotenv_values(ROOT / ".env")
    ip = str(values.get("IP_ADDRESS") or "").strip()
    key = str(values.get("UNITREE_AES_KEY") or "").strip()
    replay = Path(sys.argv[3]).resolve() if len(sys.argv) == 4 and sys.argv[2] == "--replay" else None
    if replay and not replay.is_file():
        raise ValueError("Replay database not found")
    if not replay and (not ip or not key):
        emit(state="error", message="Set IP_ADDRESS and UNITREE_AES_KEY in the Mac's .env file.")
        return 1
    env.pop("ROBOT_IP", None)
    env.update(GO2CONNECTION__IP="mock" if replay else ip, GO2CONNECTION__AES_128_KEY="" if replay else key, VIEWER="none")
    env["PATH"] = str(SOURCE / ".venv/bin") + os.pathsep + env.get("PATH", "")
    threading.Thread(target=receive, daemon=True).start()
    for sig in (signal.SIGTERM, signal.SIGINT):
        signal.signal(sig, lambda *_: STOP.set())
    app = None
    child = None
    saved = False
    stop_confirmed = False
    cloud = {"points": [], "frame": "map", "capturedAt": 0}
    try:
        # DimOS diagnostic logs may include network details: keep them local.
        with (RUNTIME / (run_id + ".log")).open("w") as log:
            child = subprocess.Popen(
                [str(SOURCE / ".venv/bin/dimos"), "--viewer", "none",
                 *(["--replay", "--replay-db", str(replay)] if replay else []),
                 "run", "unitree-go2-map",
                 "--pgovoxelmapper.map-file=" + str(map_path).removesuffix(".map.db")],
                cwd=RUNTIME, env=env, stdin=subprocess.DEVNULL, stdout=log, stderr=log,
            )
            emit(state="starting", message="Connecting and standing up. Waiting for the mapper…", runId=run_id)
            deadline = time.monotonic() + 90
            while not STOP.is_set() and child.poll() is None and time.monotonic() < deadline:
                try:
                    app = Dimos.connect(timeout=1)
                    # Verify the expected stack has been registered before declaring readiness.
                    app.WavefrontFrontierExplorer.is_exploration_active()
                    break
                except Exception:
                    if app:
                        app.stop()
                        app = None
                    STOP.wait(1)
            if app is None:
                if not STOP.is_set():
                    emit(state="error", message="Mapper did not become ready. See the local session log.")
                return 1
            emit(state="mapping", message="Mapping is ready. Press Explore to begin walking.")
            last_cloud = 0.0
            while not STOP.is_set() and child.poll() is None:
                try:
                    command = COMMANDS.get_nowait()
                except queue.Empty:
                    command = ""
                if command == "explore":
                    app.WavefrontFrontierExplorer.begin_exploration()
                elif command == "pause":
                    if not stop_motion(app):
                        raise RuntimeError("Stop could not be confirmed")
                active = app.WavefrontFrontierExplorer.is_exploration_active()
                emit(state="exploring" if active else "mapping",
                     message="Exploring reachable frontiers." if active else "Mapping stationary. Explore can continue; Stop & Save ends the session.",
                     planner=str(app.ReplanningAStarPlanner.get_state()))
                if time.monotonic() - last_cloud >= 2:
                    points = app.peek_stream("global_map", timeout=0.1)
                    if points is not None:
                        cloud = preview(points)
                        emit(cloud=cloud)
                        save_preview(run_id, cloud)
                    last_cloud = time.monotonic()
                STOP.wait(0.5)
            if not STOP.is_set():
                emit(state="error", message="Mapping engine exited unexpectedly. Use the remote stop.")
    except Exception as exc:
        # Exception messages from transports can contain credentials. Type only in UI.
        emit(state="error", message=f"Mapper error ({type(exc).__name__}). Use the remote stop; details stay on this Mac.")
    finally:
        if app:
            stop_confirmed = stop_motion(app)
        if child and child.poll() is None:
            child.terminate()  # PGOVoxelMapper.stop flushes the database
            try:
                child.wait(timeout=25)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait(timeout=5)
        if app:
            app.stop()
        try:
            saved_map = Premap.load(map_path) if map_path.exists() else None
            saved = saved_map is not None and len(saved_map) > 0
            if saved:
                cloud = preview(saved_map.cloud())
                save_preview(run_id, cloud)
                emit(cloud=cloud)
                (RUNTIME / (run_id + ".meta.json")).write_text(json.dumps({"validated": True, "keyframes": len(saved_map)}))
        except Exception:
            saved = False
        emit(state="stopped", saved=saved, stopConfirmed=stop_confirmed,
             message=("Map saved." if saved else "No valid map was saved.") +
             (" Movement stop acknowledged." if stop_confirmed else " Movement stop unconfirmed—check the robot and use its remote."))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
